# Per-test section (V&V style: Problem Description + Results)
# ---------------------------------------------------------------------------

def _vv_section_for_test(
    test: dict,
    plots_dir: Path,
    cases_dir: Path,
    out_dir: Optional[Path] = None,
    *,
    is_first: bool = False,
    is_last: bool = False,
    level: str = "section",
) -> str:
    """Return the LaTeX source for one test section in V&V style.

    *level* controls heading depth: "section" (default) or "subsection".
    """
    lines: list[str] = []
    tid = test["id"]
    title = test["title"]

    if level == "section":
        sec, subsec = "section", "subsection"
    else:
        sec, subsec = "subsection", "subsubsection"

    lines.append(f"\\{sec}{{{title}}}")
    label = f"sec:{tid}"
    if is_first:
        label = "sec:first_test"
    lines.append(f"\\label{{{label}}}")
    if is_last:
        lines.append(f"\\label{{sec:last_test}}")
    lines.append("")

    lines.append(f"\\{subsec}{{Problem Description}}")
    lines.append("")
    lines.append(test["description"])
    lines.append("")

    ic = test.get("initial_conditions", "")
    bc = test.get("boundary_conditions", "")
    mesh = test.get("mesh_movement", "")
    execution = test.get("execution", "")

    if ic:
        lines.append("\\paragraph{Initial conditions.}")
        lines.append(ic)
        lines.append("")
    if bc:
        lines.append("\\paragraph{Boundary conditions.}")
        lines.append(bc)
        lines.append("")
    if mesh:
        lines.append("\\paragraph{Mesh movement.}")
        lines.append(mesh)
        lines.append("")
    if execution:
        lines.append("\\paragraph{Execution.}")
        lines.append(execution)
        lines.append("")

    lines.append(f"\\{subsec}{{Results}}")
    lines.append("")

    # Pass criteria as the opening of results
    pc = test.get("pass_criteria", "")
    if pc:
        lines.append("\\paragraph{Pass criteria.}")
        lines.append(pc)
        lines.append("")

    # Metrics table
    reader = METRIC_READERS.get(tid)
    if reader is not None:
        metric_rows = reader(cases_dir)
        if metric_rows:
            lines.append("\\paragraph{Achieved results.}")
            lines.append(_metrics_table_tex(metric_rows))
            lines.append("")
        else:
            lines.append(
                "\\textit{No metric output files found --- "
                "run the test suite first.}"
            )
            lines.append("")

    # Plots
    plot_files = test.get("plots", [])
    caption = test.get("plot_caption", "")
    extra_plot_dir = test.get("plot_dir")

    if plot_files:
        available: list[Path] = []
        search_dirs = [plots_dir]
        if extra_plot_dir:
            search_dirs.append(cases_dir / extra_plot_dir)
        for pf in plot_files:
            stem = Path(pf).stem
            for sd in search_dirs:
                pdf_path = sd / f"{stem}.pdf"
                png_path = sd / pf
                if pdf_path.is_file():
                    if out_dir is not None:
                        available.append(
                            Path(os.path.relpath(
                                pdf_path.resolve(), out_dir.resolve()))
                        )
                    else:
                        available.append(pdf_path)
                    break
                elif png_path.is_file():
                    if out_dir is not None:
                        available.append(
                            Path(os.path.relpath(
                                png_path.resolve(), out_dir.resolve()))
                        )
                    else:
                        available.append(png_path)
                    break

        if available:
            lines.append("\\begin{figure}[htbp]")
            lines.append("  \\centering")
            n_plots = len(available)
            if n_plots == 1:
                lines.append(
                    f"  \\includegraphics[width=0.95\\textwidth]"
                    f"{{{available[0]}}}"
                )
            elif n_plots == 2:
                for p in available:
                    lines.append(
                        f"  \\includegraphics[width=0.48\\textwidth]{{{p}}}"
                    )
                    lines.append("  \\hfill")
            else:
                for idx, p in enumerate(available):
                    lines.append(
                        f"  \\includegraphics[width=0.48\\textwidth]{{{p}}}"
                    )
                    if idx % 2 == 0 and idx + 1 < n_plots:
                        lines.append("  \\hfill")
                    elif idx + 1 < n_plots:
                        lines.append("  \\\\[6pt]")
            if caption:
                lines.append(f"  \\caption{{{caption}}}")
            lines.append(f"  \\label{{fig:{tid}}}")
            lines.append("\\end{figure}")
            lines.append("")
        else:
            lines.append(
                "\\textit{Plots not available --- "
                "run the test suite and the plot generator first.}"
            )
            lines.append("")
    else:
        lines.append("\\textit{This test does not produce comparison plots.}")
        lines.append("")

    lines.append("\\newpage")
    lines.append("")
    return "\n".join(lines)


