def _overview_table() -> str:
    """Return a LaTeX summary table listing every test, grouped by category."""
    lines = [
        r"\begin{table}[htbp]",
        r"\centering",
        r"\caption{Overview of all regression tests.}",
        r"\label{tab:vv_overview}",
        r"\small",
        r"\begin{tabular}{l l l l l}",
        r"\toprule",
        (r"\textbf{Test} & \textbf{Mode} & \textbf{CPUs} "
         r"& \textbf{Mesh} & \textbf{Plots} \\"),
        r"\midrule",
    ]

    for cat_idx, (cat_name, cat_ids) in enumerate(TEST_CATEGORIES):
        lines.append(r"\multicolumn{5}{l}{\textit{" + cat_name + r"}} \\")
        for entry in cat_ids:
            if entry in TEST_GROUPS:
                _, sub_ids = TEST_GROUPS[entry]
                for tid in sub_ids:
                    row = _TABLE_ROWS[tid]
                    lines.append(r"\quad " + " & ".join(row) + r" \\")
            else:
                row = _TABLE_ROWS[entry]
                lines.append(r"\quad " + " & ".join(row) + r" \\")
        if cat_idx < len(TEST_CATEGORIES) - 1:
            lines.append(r"\addlinespace")

    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}",
        "",
        r"\newpage",
        "",
    ]
    return "\n".join(lines)


