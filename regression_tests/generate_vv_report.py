def generate_vv_tex(
    plots_dir: Path,
    cases_dir: Path,
    out_dir: Optional[Path] = None,
) -> str:
    """Return the full V&V LaTeX document as a string."""
    test_by_id = {t["id"]: t for t in TESTS}
    parts = [PREAMBLE, INTRODUCTION, _overview_table(), INFRASTRUCTURE]

    all_test_ids: list[str] = []
    for _, cat_ids in TEST_CATEGORIES:
        for entry in cat_ids:
            if entry in TEST_GROUPS:
                all_test_ids.extend(TEST_GROUPS[entry][1])
            else:
                all_test_ids.append(entry)
    total_tests = len(all_test_ids)
    global_idx = 0

    for cat_name, cat_ids in TEST_CATEGORIES:
        parts.append(f"\n\\part{{{cat_name}}}\n\\setcounter{{section}}{{0}}\n\\newpage\n")
        for entry in cat_ids:
            if entry in TEST_GROUPS:
                group_title, sub_ids = TEST_GROUPS[entry]
                parts.append(f"\\section{{{group_title}}}")
                parts.append(f"\\label{{sec:{entry}}}")
                if global_idx == 0:
                    parts.append("\\label{sec:first_test}")
                parts.append("")
                for sub_tid in sub_ids:
                    test = test_by_id[sub_tid]
                    parts.append(
                        _vv_section_for_test(
                            test, plots_dir, cases_dir, out_dir,
                            is_first=False,
                            is_last=(global_idx == total_tests - 1),
                            level="subsection",
                        )
                    )
                    global_idx += 1
            else:
                test = test_by_id[entry]
                parts.append(
                    _vv_section_for_test(
                        test, plots_dir, cases_dir, out_dir,
                        is_first=(global_idx == 0),
                        is_last=(global_idx == total_tests - 1),
                    )
                )
                global_idx += 1

    parts.append(_summary_section())
    parts.append(BIBLIOGRAPHY)
    parts.append(AGENTIC_APPENDIX)
    parts.append(POSTAMBLE)
    return "\n".join(parts)


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> int:
    parser = argparse.ArgumentParser(
        description="Generate a V&V LaTeX report for the RICH regression test suite."
    )
    parser.add_argument(
        "--output-dir",
        default=None,
        help="Directory to write .tex and .pdf into (default: regression_tests/).",
    )
    parser.add_argument(
        "--no-compile",
        action="store_true",
        help="Only generate the .tex file; do not run pdflatex.",
    )
    parser.add_argument(
        "--no-plots",
        action="store_true",
        help="Skip running plot_results.py (assume plots already exist).",
    )
    parser.add_argument(
        "--plots-dir",
        default=None,
        help="Directory containing plot PNGs (default: regression_tests/plots/).",
    )
    args = parser.parse_args()

    root = repo_root()
    regression_dir = root / "regression_tests"

    if args.output_dir:
        out_dir = Path(args.output_dir)
    else:
        out_dir = regression_dir
    out_dir.mkdir(parents=True, exist_ok=True)

    if args.plots_dir:
        plots_dir = Path(args.plots_dir)
    else:
        plots_dir = regression_dir / "plots"

    # Step 1: generate plots
    if not args.no_plots:
        print("Generating plots via plot_results.py ...")
        plots_dir.mkdir(parents=True, exist_ok=True)
        plot_script = regression_dir / "plot_results.py"
        if plot_script.is_file():
            result = subprocess.run(
                [sys.executable, str(plot_script), "--all",
                 "--output-dir", str(plots_dir)],
                cwd=str(root),
                capture_output=True,
                text=True,
            )
            print(result.stdout)
            if result.returncode != 0:
                print(
                    f"Warning: plot_results.py exited with code "
                    f"{result.returncode}",
                    file=sys.stderr,
                )
                if result.stderr:
                    print(result.stderr, file=sys.stderr)
        else:
            print(
                f"Warning: plot script not found at {plot_script}",
                file=sys.stderr,
            )
    else:
        print("Skipping plot generation (--no-plots).")

    # Step 2: generate .tex
    cases_dir = regression_dir / "cases"
    tex_path = out_dir / "vv_report.tex"
    tex_content = generate_vv_tex(plots_dir, cases_dir, out_dir)
    tex_path.write_text(tex_content, encoding="utf-8")
    print(f"Wrote {tex_path}")

    # Step 3: compile to PDF
    if not args.no_compile:
        pdflatex = shutil.which("pdflatex")
        if pdflatex is None:
            print(
                "pdflatex not found; skipping PDF compilation. "
                "Install a TeX distribution to compile the .tex file.",
                file=sys.stderr,
            )
            return 0

        print("Compiling LaTeX to PDF ...")
        for pass_num in (1, 2):
            result = subprocess.run(
                [pdflatex, "-interaction=nonstopmode",
                 "-output-directory", str(out_dir),
                 str(tex_path)],
                cwd=str(out_dir),
                capture_output=True,
                text=True,
            )
            if result.returncode != 0:
                print(
                    f"pdflatex pass {pass_num} exited with code "
                    f"{result.returncode}",
                    file=sys.stderr,
                )
                log_file = out_dir / "vv_report.log"
                if log_file.is_file():
                    print(f"See {log_file} for details.", file=sys.stderr)
                if pass_num == 1:
                    return 1

        pdf_path = out_dir / "vv_report.pdf"
        if pdf_path.is_file():
            print(f"PDF generated: {pdf_path}")
        else:
            print(
                "Warning: PDF file not found after compilation.",
                file=sys.stderr,
            )
    else:
        print("Skipping PDF compilation (--no-compile).")

    return 0


if __name__ == "__main__":
    sys.exit(main())
